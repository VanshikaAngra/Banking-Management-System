-- ==========================================================
-- 11. TRANSACTION HISTORY USING CURSOR
-- ==========================================================

DELIMITER $$

CREATE PROCEDURE SHOW_HISTORY(
    IN P_ID INT
)
BEGIN

    DECLARE V_DONE INT DEFAULT 0;
    DECLARE V_TID INT;
    DECLARE V_TYPE VARCHAR(20);
    DECLARE V_AMOUNT DECIMAL(12,2);
    DECLARE V_DATE DATETIME;

    DECLARE C_HISTORY CURSOR FOR
        SELECT TRANSACTION_ID,
               TRANSACTION_TYPE,
               AMOUNT,
               TRANSACTION_DATE
        FROM TRANSACTIONS
        WHERE ACCOUNT_ID = P_ID
        ORDER BY TRANSACTION_ID;

    DECLARE CONTINUE HANDLER FOR NOT FOUND
        SET V_DONE = 1;

    OPEN C_HISTORY;

    HISTORY_LOOP: LOOP

        FETCH C_HISTORY
        INTO V_TID, V_TYPE, V_AMOUNT, V_DATE;

        IF V_DONE = 1 THEN
            LEAVE HISTORY_LOOP;
        END IF;

        SELECT V_TID AS TRANSACTION_ID,
               V_TYPE AS TRANSACTION_TYPE,
               V_AMOUNT AS AMOUNT,
               V_DATE AS TRANSACTION_DATE;

    END LOOP;

    CLOSE C_HISTORY;

END$$

